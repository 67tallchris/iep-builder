#!/usr/bin/env python3
"""Prepare build data for the IEP Builder app.

- Bundles research/exemplars/*.json into public/data/examples.json
- Copies research/boilerplate/snippets.json into public/data/snippets.json
- Generates seed.sql for D1 (examples + snippets)

Run: npm run data  (or python3 scripts/prepare_data.py)
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EX_DIR = os.path.join(ROOT, "research", "exemplars")
SNIPPETS = os.path.join(ROOT, "research", "boilerplate", "snippets.json")
PUBLIC_DATA = os.path.join(ROOT, "public", "data")
SEED = os.path.join(ROOT, "seed.sql")

os.makedirs(PUBLIC_DATA, exist_ok=True)


def sql_str(value):
    if value is None:
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def load_examples():
    examples = []
    for f in sorted(glob.glob(os.path.join(EX_DIR, "0*.json"))):
        for e in json.load(open(f))["exemplars"]:
            examples.append(e)
    band_order = {"elementary": 0, "middle": 1, "high": 2}
    examples.sort(key=lambda e: (band_order.get(e.get("grade_band"), 9), e.get("grade") or 0, e["id"]))
    return examples


def main():
    examples = load_examples()
    bundle = {
        "version": "1.0",
        "disclaimer": "Fictional synthetic exemplars. No real student data. Not legal advice.",
        "count": len(examples),
        "examples": examples,
    }
    with open(os.path.join(PUBLIC_DATA, "examples.json"), "w") as f:
        json.dump(bundle, f, ensure_ascii=False)

    with open(SNIPPETS) as f:
        snippets = json.load(f)
    with open(os.path.join(PUBLIC_DATA, "snippets.json"), "w") as f:
        json.dump(snippets, f, ensure_ascii=False)

    lines = [
        "-- generated by scripts/prepare_data.py",
        "DELETE FROM examples;",
        "DELETE FROM snippets;",
    ]
    for i, e in enumerate(examples):
        lines.append(
            "INSERT INTO examples (id,title,grade,grade_band,az_category,document_type,"
            "has_behavior_plan,payload,sort_order) VALUES ("
            f"{sql_str(e['id'])},{sql_str(e['title'])},{e.get('grade') if e.get('grade') is not None else 'NULL'},"
            f"{sql_str(e.get('grade_band'))},{sql_str(e.get('az_category'))},"
            f"{sql_str(e.get('document_type', 'iep'))},"
            f"{1 if e.get('behavior_support_plan') else 0},"
            f"{sql_str(json.dumps(e, ensure_ascii=False))},{i});"
        )
    for s in snippets["snippets"]:
        lines.append(
            "INSERT INTO snippets (id,component,category,grade_band,text,payload) VALUES ("
            f"{sql_str(s['id'])},{sql_str(s.get('component'))},{sql_str(s.get('category'))},"
            f"{sql_str(s.get('grade_band'))},{sql_str(s.get('text'))},"
            f"{sql_str(json.dumps(s, ensure_ascii=False))});"
        )
    with open(SEED, "w") as f:
        f.write("\n".join(lines) + "\n")

    print(f"examples.json: {len(examples)} examples")
    print(f"snippets.json: {snippets['count']} snippets")
    print(f"seed.sql: {len(lines) - 3} rows")


if __name__ == "__main__":
    main()
